import { readFile, writeFile } from 'node:fs/promises';

// Developer tooling only: the application embeds the JSON and never runs this script.
const check = process.argv.includes('--check');
if (process.argv.slice(2).some((arg) => arg !== '--check')) {
  throw new Error('Usage: node scripts/recognition-coverage.mjs [--check]');
}
const catalog = JSON.parse(
  await readFile(new URL('../rules/recognition.json', import.meta.url), 'utf8'),
);
const categories = new Map([
  ['windows', 'Windows 与安装维护'],
  ['development', '开发工具与构建'],
  ['ai', 'AI 模型与工作流'],
  ['virtualization', '虚拟机与子系统'],
  ['games', '游戏与启动器'],
  ['applications', '应用资料与邮件'],
  ['media', '音视频、设计与工程素材'],
  ['documents', '办公文档'],
  ['data', '数据库与数据集'],
  ['archives', '归档与备份'],
]);
const matchers = {
  extension: '文件后缀',
  file_name: '完整文件名',
  directory_sequence: '连续目录片段',
  drive_root_file: '盘符根文件',
};
for (const rule of catalog.rules) {
  if (!categories.has(rule.category) || !matchers[rule.matcher]) {
    throw new Error(`Unknown category or matcher: ${rule.id}`);
  }
}
const patternCount = (rules) => rules.reduce((total, rule) => total + rule.patterns.length, 0);
const cell = (value) => value.replaceAll('|', '&#124;').replaceAll('\n', ' ');
const code = (value) => '`' + cell(value).replaceAll('`', '&#96;') + '`';
const lines = [
  '# 离线用途覆盖矩阵',
  '',
  '<!-- Generated by scripts/recognition-coverage.mjs; edit the catalog and regenerate. -->',
  '',
  `规则库修订：${code(catalog.revision)}。共 **${catalog.rules.length} 条用途规则、${patternCount(catalog.rules)} 个主匹配项**，按用途分为 ${categories.size} 类。主匹配项数不重复计算 \`within\` 条件。规则数量不等于软件数量，也不代表对任意磁盘的识别率。`,
  '',
  '全部匹配只使用扫描索引中的路径和文件/目录类型；不验证内容、安装状态或是否还在使用。来源解释通用用途，常见路径可以被用户重命名或更改，因此结果仍显示“可能”。',
  '',
  '| 类别 | 规则数 | 主匹配项 |',
  '| --- | ---: | ---: |',
];
for (const [category, title] of categories) {
  const rules = catalog.rules.filter((rule) => rule.category === category);
  lines.push(`| ${title} | ${rules.length} | ${patternCount(rules)} |`);
}
for (const [category, title] of categories) {
  lines.push(
    '',
    `## ${title}`,
    '',
    '| 规则 ID | 用途 | 匹配项与条件 | 参考来源 |',
    '| --- | --- | --- | --- |',
  );
  for (const rule of catalog.rules.filter((rule) => rule.category === category)) {
    let condition = `${matchers[rule.matcher]}：${rule.patterns.map(code).join('、')}`;
    if (rule.within?.length) condition += `；同时位于 ${rule.within.map(code).join(' 或 ')}`;
    if (rule.priority !== undefined) condition += `；优先级 ${rule.priority}`;
    lines.push(
      `| ${code(rule.id)} | ${cell(rule.title)} | ${condition} | [资料](${rule.source}) |`,
    );
  }
}
lines.push(
  '',
  '## 当前边界',
  '',
  '- 可识别常见格式和已列出的路径结构，不承诺覆盖所有软件或自定义存储布局。通用文档、数据库、音视频格式仅说明类型，不推断它是否属于某个具体应用。',
  '- 用途识别按目录结构与文件特征匹配，不要求软件版本在白名单内；核实版本仅记录样本来源。目录中的 `_{version}` 匹配数字或点分数字后缀，可沿用到结构相同的其他版本。',
  '- `within` 是路径条件，不是读取文件或检测相邻标记文件。尚未加入文件头识别、安装器查询或目录内容探测。',
  '- 单独的 Cache、data、target、.bin、.dat、.bak、.sav 等不据此认定用途。某些文件位于明确的应用目录时可由该目录规则解释。',
  '- 清理资格仍仅来自原有规则。模型、虚拟磁盘、邮件、数据库、备份、开发仓库等即使识别成功，也不会增加删除入口。',
  '',
);
const output = lines.join('\n');
const target = new URL('../docs/recognition-coverage.md', import.meta.url);
if (check) {
  if ((await readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== output) {
    throw new Error('Coverage matrix is stale; run node scripts/recognition-coverage.mjs');
  }
} else {
  await writeFile(target, output, 'utf8');
}
console.log(
  `${check ? 'Checked' : 'Generated'} ${catalog.rules.length} rules, ${patternCount(catalog.rules)} patterns.`,
);
